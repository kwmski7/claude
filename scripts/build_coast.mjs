// Builds web/data/coast.js: Natural Earth 10m coastlines and land borders
// (via world-atlas) clipped to the Korean peninsula region, simplified and
// delta-encoded so the page can draw them on a canvas without a map library.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature, mesh } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-10m.json"), "utf8"));

const BBOX = { w: 119.5, e: 135.5, s: 28.5, n: 43.5 }; // generous: phones show more latitude
const TOL = 0.006;   // simplification tolerance in degrees (~0.6 km)
const Q = 1000;      // quantisation: 0.001 degree

const inside = ([x, y]) => x >= BBOX.w && x <= BBOX.e && y >= BBOX.s && y <= BBOX.n;

// Split a polyline wherever it leaves the bbox (we only stroke lines, never fill).
function clip(line) {
  const out = []; let cur = [];
  for (let i = 0; i < line.length; i++) {
    const p = line[i];
    const keep = inside(p) || (i > 0 && inside(line[i - 1])) || (i < line.length - 1 && inside(line[i + 1]));
    if (keep) cur.push(p); else if (cur.length) { out.push(cur); cur = []; }
  }
  if (cur.length) out.push(cur);
  return out.filter((l) => l.length > 1);
}

// Douglas–Peucker
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len2 = dx * dx + dy * dy;
    let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      let t = len2 ? ((px - ax) * dx + (py - ay) * dy) / len2 : 0;
      t = Math.max(0, Math.min(1, t));
      const ex = px - (ax + t * dx), ey = py - (ay + t * dy), d = ex * ex + ey * ey;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol * tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

function encode(lines, minPts) {
  const res = [];
  for (const raw of lines) for (const part of clip(raw)) {
    const s = simplify(part, TOL);
    if (s.length < minPts) continue;
    const flat = []; let px = 0, py = 0;
    for (const [x, y] of s) {
      const qx = Math.round(x * Q), qy = Math.round(y * Q);
      flat.push(qx - px, qy - py); px = qx; py = qy;
    }
    res.push(flat);
  }
  return res;
}

const countries = topo.objects.countries;
// Coastlines: outer rings of land polygons (every country ring is coastline or border;
// we take the exterior mesh, i.e. arcs used by only one country).
const coastMesh = mesh(topo, countries, (a, b) => a === b);
const borderMesh = mesh(topo, countries, (a, b) => a !== b);

const coast = encode(coastMesh.coordinates, 3);
const border = encode(borderMesh.coordinates, 2);
const pts = (ls) => ls.reduce((n, l) => n + l.length / 2, 0);

const payload = { q: Q, source: "Natural Earth 10m via world-atlas 2.0.2", bbox: BBOX, coast, border };
const js = "// Generated by scripts/build_coast.mjs — do not edit.\nwindow.COAST=" + JSON.stringify(payload) + ";\n";
writeFileSync(new URL("../web/data/coast.js", import.meta.url), js);
console.log(`coast: ${coast.length} lines, ${pts(coast)} pts; border: ${border.length} lines, ${pts(border)} pts; ${(js.length / 1024).toFixed(0)} KB`);
